// node scripts/capture_ask_cache.mjs [endpoint]
// Records real answers from the deployed Ask IGNIS worker for the six preset
// questions and the three mission buttons, in English and Polish, and writes
// app/data/ask_cache.js — the page's fallback when the network fails or the
// 25 s limit passes. Nothing here is written by hand: an answer with an
// unresolved citation, oxygen written as a fraction, or a cut-off ending is
// retried, and if it still fails it is left out of the file.
// The question texts must match ASK_PRESETS and MISSIONS in app/app.js.
import fs from "node:fs";

const URL_ = process.argv[2] || "https://ignis-ask.ignis-ask.workers.dev";
const OUT = new URL("../app/data/ask_cache.js", import.meta.url);
const PRESETS = {
  rank: ["Rank the investigations most relevant to a lunar base at 30% O₂ and 10.2 psi, and say what each can and cannot tell us.",
         "Uszereguj badania najważniejsze dla bazy księżycowej przy 30% O₂ i 10,2 psi i powiedz, co każde może, a czego nie może nam powiedzieć."],
  extract: ["Which test points could feed a flammability model for a Mars habitat cabin, and what oxygen and pressure ranges do they cover?",
            "Które punkty testowe mogą zasilić model palności dla kabiny habitatu na Marsie i jakie zakresy tlenu i ciśnienia pokrywają?"],
  interpret: ["What do these findings imply for the next generation of fire detection and suppression equipment?",
              "Co te wyniki oznaczają dla następnej generacji sprzętu do wykrywania i gaszenia pożarów?"],
  earth: ["What does this microgravity research mean for fire safety on Earth?",
          "Co te badania w mikrograwitacji znaczą dla bezpieczeństwa pożarowego na Ziemi?"],
  gap: ["What single test would most reduce the uncertainty for materials in a 30% oxygen cabin?",
        "Jaki pojedynczy test najbardziej zmniejszyłby niepewność dla materiałów w kabinie z 30% tlenu?"],
  beyond: ["How would polyurethane foam burn at 30% O₂ and 10.2 psi, compared with Nomex?",
           "Jak paliłaby się pianka poliuretanowa przy 30% O₂ i 10,2 psi w porównaniu z Nomexem?"],
};
const MISSIONS = {
  rover: ["Pressurized rover", "Łazik ciśnieniowy"],
  base: ["Lunar surface base", "Baza księżycowa"],
  transit: ["Transit cabin", "Kabina tranzytowa"],
};
const only = process.argv[3]; // e.g. "ask:gap:pl" to refresh one entry

const post = async (body) => {
  const t0 = Date.now();
  const r = await fetch(URL_, { method: "POST", headers: { "Content-Type": "application/json", "User-Agent": "Mozilla/5.0", Origin: "null" },
                                body: JSON.stringify(body), signal: AbortSignal.timeout(150000) });
  const j = await r.json().catch(() => ({ error: "http_" + r.status }));
  return { j, s: Math.round((Date.now() - t0) / 100) / 10 };
};
const clean = (c) => !c || ((c.unknown_investigations || []).length + (c.unknown_quotes || []).length
  + (c.unverified_free_quotes || []).length + (c.fraction_oxygen || []).length
  + (c.quote_credited_to_other_study || []).length === 0);

let prev = { ask: {}, rank: {} };
if (fs.existsSync(OUT)) { const s = fs.readFileSync(OUT, "utf8"); prev = JSON.parse(s.slice(s.indexOf("{"), s.lastIndexOf("}") + 1)); }
const cache = { ask: { ...prev.ask }, rank: { ...prev.rank } };
const today = new Date().toISOString().slice(0, 10);

for (const [kind, table] of [["ask", PRESETS], ["rank", MISSIONS]]) {
  for (const [key, texts] of Object.entries(table)) {
    for (const [li, lang] of [[0, "en"], [1, "pl"]]) {
      const id = `${key}:${lang}`;
      if (only && only !== `${kind}:${id}`) continue;
      let kept = null;
      for (let attempt = 1; attempt <= 3 && !kept; attempt++) {
        const body = kind === "ask" ? { question: texts[li], lang } : { mode: "rank", mission: texts[li], lang };
        const { j, s } = await post(body);
        const ok = !j.error && clean(j.check) && !j.truncated;
        console.log(JSON.stringify({ kind, id, attempt, s, ok, error: j.error, queries: j.queries, check: j.check && { u: j.check.unsourced_numbers, f: j.check.fraction_oxygen, q: j.check.unverified_free_quotes } }));
        if (ok) kept = kind === "ask"
          ? { question: texts[li], answer: j.answer, check: j.check, model: j.model, queries: j.queries, seconds: s, saved: today }
          : { mission: texts[li], ranking: j.ranking, check: j.check, model: j.model, queries: j.queries, seconds: s, saved: today };
      }
      if (kept) cache[kind][id] = kept;
      else { delete cache[kind][id]; console.log(`left out ${kind}:${id}`); }
    }
  }
}
fs.writeFileSync(OUT, "// Generated by scripts/capture_ask_cache.mjs from the deployed Ask IGNIS worker.\n" +
  "// Real answers, saved with their check, model and date; shown only when the live call fails.\n" +
  "window.ASK_CACHE = " + JSON.stringify(cache, null, 1) + ";\n");
console.log(`wrote ${Object.keys(cache.ask).length} answers, ${Object.keys(cache.rank).length} rankings`);
